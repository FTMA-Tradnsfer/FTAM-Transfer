async function repay(loan,button){
 if(!loan||busy)return;
 if(!confirm(`총 ${money(loan.total_due)}을 상환하시겠습니까?`))return;
 busy=true;
 if(button){button.disabled=true;button.textContent='상환 처리 중...';}
 try{
  const r=await db.rpc('finance_club_repay',{p_session_token:token(),p_loan_id:loan.id});
  if(r.error)throw r.error;
  if(r.data?.success===false)throw new Error(r.data.message||'대출 상환에 실패했습니다.');
  selectedLoan=null;
  alert(`${money(loan.total_due)} 상환이 완료되었습니다.`);
  await load();
 }catch(e){
  console.error('FTMA club debt repayment failed',e);
  alert(e.message||'대출 상환에 실패했습니다.');
  if(button){button.disabled=false;button.textContent='빚 상환';}
 }finally{busy=false;}
}
/* Catch the final confirmation button generated by older UI code as well. */
document.addEventListener('click',e=>{
 const el=e.target?.closest?.('button');
 if(!el||el.textContent.trim()!=='빚 상환'||busy)return;
 const rowButton=el.closest('[data-debt-id]');
 if(rowButton){selectedLoan=loans.find(x=>String(x.id)===String(rowButton.dataset.debtId))||selectedLoan;return;}
 if(selectedLoan){e.preventDefault();e.stopImmediatePropagation();repay(selectedLoan,el);}
},true);
